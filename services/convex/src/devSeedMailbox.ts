export function isolatedMailbox(now: number) {
  return SEEDS.map((seed: Seed, index) => {
    const id = `isolated-${index}`;
    const [name, address] = seed.from;
    return {
      account: seed.account,
      remoteMessageId: id,
      remoteThreadId: `isolated-thread-${seed.thread ?? index}`,
      internetMessageId: `<${id}@seed.example>`,
      from: { address, name },
      subject: seed.subject,
      snippet: seed.snippet,
      body: seed.body ?? `${seed.snippet}\n\n— ${name.split(" ")[0]}`,
      receivedAt: Math.round(now - seed.hoursAgo * 60 * 60 * 1000),
      isRead: seed.unread !== true,
      isPinned: seed.pinned === true,
      category: seed.category,
      importance: seed.category === "noise" ? 0.05 : 0.5,
      confidence: 0.9,
      reason: "Seeded demo mail.",
      summary: seed.snippet,
      shouldEmbed: false,
      ...(seed.attachment ? { attachment: seed.attachment } : {}),
      ...(seed.placement ? { placement: seed.placement } : {}),
      recipientName: ISOLATED_OWNER_NAME,
    } satisfies DemoMessage;
  });
}
