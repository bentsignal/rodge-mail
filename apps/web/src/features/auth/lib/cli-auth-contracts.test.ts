import { describe, expect, it } from "vitest";

import {
  cliAuthRequestSearchSchema,
  createCliAuthCallbackUrl,
} from "./cli-auth-contracts";

const requestId = "r".repeat(43);
const authorizationCode = "A_-".repeat(14) + "A";
const callbackUrl = "http://127.0.0.1:43123/auth/desktop-complete";

describe("CLI auth route contracts", () => {
  it("accepts the fixed-length base64url request generated by the CLI", () => {
    expect(
      cliAuthRequestSearchSchema.parse({
        callback_url: callbackUrl,
        request_id: requestId,
      }),
    ).toEqual({ callback_url: callbackUrl, request_id: requestId });
  });

  it("requires a callback URL", () => {
    expect(
      cliAuthRequestSearchSchema.safeParse({ request_id: requestId }).success,
    ).toBe(false);
  });

  it("accepts only a fixed loopback callback URL", () => {
    for (const invalidCallback of [
      "https://127.0.0.1:43123/auth/desktop-complete",
      "http://localhost:43123/auth/desktop-complete",
      "http://127.0.0.1/auth/desktop-complete",
      "http://127.0.0.1:43123/other",
      "http://127.0.0.1:43123/auth/desktop-complete?extra=true",
    ]) {
      expect(
        cliAuthRequestSearchSchema.safeParse({
          callback_url: invalidCallback,
          request_id: requestId,
        }).success,
      ).toBe(false);
    }
  });

  it.each([
    "short",
    "r".repeat(42),
    "r".repeat(44),
    `${"r".repeat(42)}+`,
    `${"r".repeat(42)}=`,
  ])("rejects an invalid CLI request token %s", (invalidToken) => {
    expect(
      cliAuthRequestSearchSchema.safeParse({
        callback_url: callbackUrl,
        request_id: invalidToken,
      }).success,
    ).toBe(false);
  });

  it("requires both valid callback credentials", () => {
    expect(() =>
      createCliAuthCallbackUrl(callbackUrl, requestId, "short"),
    ).toThrow();
  });

  it("encodes an approved callback for the CLI loopback listener", () => {
    const callback = new URL(
      createCliAuthCallbackUrl(callbackUrl, requestId, authorizationCode),
    );

    expect(callback.origin).toBe("http://127.0.0.1:43123");
    expect(callback.pathname).toBe("/auth/desktop-complete");
    expect(callback.searchParams.get("request_id")).toBe(requestId);
    expect(callback.searchParams.get("authorization_code")).toBe(
      authorizationCode,
    );
  });
});
